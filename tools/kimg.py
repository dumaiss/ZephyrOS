#!/usr/bin/env python3
"""KIMG v1 host converter (the target-side format is kos/kimg.h).

The picture viewer's images are prepared on the host: the Z80 decodes
nothing.  The converter reads any format Pillow reads (PNG, JPEG, ...),
center-crops the source to the target mode's aspect ratio, scales it to
the mode's size and packs the payload:

    g6   GRAPHIC 6, 512 x 212, 4 bpp: an adaptive 16-colour palette
         (Pillow's median cut, no dither) written before the payload,
         which packs two palette indices per byte (high nibble first);
    g7   GRAPHIC 7, 256 x 212, 8 bpp: one byte per pixel, green in bits
         7-5, red in bits 4-2, blue in bits 1-0 (the V9958's GRB 3-3-2);
    yjk  GRAPHIC 7 + YJK, 256 x 212, the width a multiple of 4: each
         byte carries its pixel's 5-bit luminance Y in bits 7-3; each
         run of four pixels shares two 6-bit signed colour differences,
         K (bits 2-0 of the first byte low, of the second high) and J
         (third low, fourth high).  The V9958 shows R = Y + J,
         G = Y + K, B = (5Y - 2J - K) / 4 (5-bit, clamped).  J and K
         come from the run's average colour; each pixel's Y is the one
         whose decoded colour is nearest its own.

Usage:
    kimg.py convert SOURCE OUTPUT --mode {g6,g7,yjk} [--size WxH]
                    [--resample {nearest,box,lanczos}] [--sharpen]
                    [--sharpen-radius FLOAT] [--sharpen-percent INTEGER]
                    [--sharpen-threshold INTEGER]
                    [--yjk-quality {fast,optimized}]
    kimg.py pack SOURCE OUTPUT --mode {g6,g7,yjk} [--size WxH]
                 [--palette RGB_FILE]
    kimg.py info FILE

The default size is the mode's screen; `--size` makes a rectangle
(useful for fixtures).  The conversion is deterministic for a pinned
Pillow version; the committed test fixtures are never regenerated by
the build.

`pack` wraps headerless, tightly packed native pixel bytes unchanged: no
cropping, scaling, colour conversion or pixel repacking. The default size
is the mode's screen; specify --size for other dimensions. A G6 palette
may be supplied as 1-16 RGB888 triples (3-48 bytes, R/G/B order), copied
unchanged before the pixels. Without it, the file has no palette override.
G7 and YJK do not accept a palette. BSAVE headers, row padding and
embedded palettes must be removed from the input before packing.

Only `convert` requires Pillow (it is not a build dependency).

Conversion defaults remain nearest resampling, no sharpening and fast YJK.
Box averages source pixels (useful for integer-ratio reduction); Lanczos
gives smoother reduction but may ring. Optional unsharp masking can improve
small lettering, with possible halos. Optimized YJK rounds RGB888 to RGB555
and searches shared chroma and individual luminance, using more host time
without changing the runtime format. Same-size inputs bypass resizing.
"""

import argparse
from functools import lru_cache
import math
import struct
import sys

try:
    from PIL import Image, ImageFilter
except ImportError:  # pragma: no cover - the host simply lacks Pillow
    Image = None

MAGIC = b"KIMG"
VERSION = 1
FLAGS = 0

MODES = {
    "g6": (0, 512, 212),
    "g7": (1, 256, 212),
    "yjk": (2, 256, 212),
}

# Each YJK colour difference pair covers this many pixels.
YJK_RUN = 4


def require_pillow():
    if Image is None:
        raise SystemExit("kimg: Pillow is required (pip install Pillow)")


def _fit(image, size, resample="nearest"):
    """Center-crop to the target aspect ratio, then scale exactly."""
    target_width, target_height = size
    source_width, source_height = image.size
    if image.size == size:
        return image
    target_ratio = target_width / target_height
    source_ratio = source_width / source_height
    if source_ratio > target_ratio:
        crop_width = int(source_height * target_ratio)
        left = (source_width - crop_width) // 2
        box = (left, 0, left + crop_width, source_height)
    else:
        crop_height = int(source_width / target_ratio)
        top = (source_height - crop_height) // 2
        box = (0, top, source_width, top + crop_height)
    cropped = image.crop(box)
    if cropped.size == size:
        return cropped
    filters = {"nearest": Image.Resampling.NEAREST,
               "box": Image.Resampling.BOX,
               "lanczos": Image.Resampling.LANCZOS}
    return cropped.resize(size, filters[resample])


def _pack_g6(rgb, size):
    quantized = rgb.quantize(16, method=Image.Quantize.MEDIANCUT,
                             dither=Image.Dither.NONE).convert("P")
    palette = quantized.getpalette()[: 16 * 3]
    indices = quantized.tobytes()
    payload = bytearray()
    for index in range(0, len(indices), 2):
        payload.append((indices[index] << 4) | indices[index + 1])
    return palette, bytes(payload)


def _pack_g7(rgb, size):
    payload = bytearray()
    raw = rgb.tobytes()
    for offset in range(0, len(raw), 3):
        r, g, b = raw[offset], raw[offset + 1], raw[offset + 2]
        payload.append(((g >> 5) << 5) | ((r >> 5) << 2) | (b >> 6))
    return [], bytes(payload)


def yjk_decode(y, j, k):
    """The V9958's YJK to 5-bit RGB, clamped (J and K signed)."""
    def clamp(value):
        return 0 if value < 0 else 31 if value > 31 else value
    return (clamp(y + j), clamp(y + k), clamp((5 * y - 2 * j - k) // 4))


def _yjk_run(pixels):
    """Four 5-bit (r, g, b) pixels -> their four YJK bytes."""
    count = len(pixels)
    r = sum(p[0] for p in pixels) / count
    g = sum(p[1] for p in pixels) / count
    b = sum(p[2] for p in pixels) / count
    y = b / 2 + r / 4 + g / 8
    j = max(-32, min(31, round(r - y)))
    k = max(-32, min(31, round(g - y)))
    lows = (k & 7, (k >> 3) & 7, j & 7, (j >> 3) & 7)
    out = bytearray()
    for (pr, pg, pb), low in zip(pixels, lows):
        start = round(pb / 2 + pr / 4 + pg / 8)
        best = None
        for candidate in range(max(0, start - 4), min(31, start + 4) + 1):
            dr, dg, db = yjk_decode(candidate, j, k)
            error = (dr - pr) ** 2 + (dg - pg) ** 2 + (db - pb) ** 2
            if best is None or error < best[0]:
                best = (error, candidate)
        out.append((best[1] << 3) | low)
    return out


# Keep the decoder identical for both paths. Its blue-channel floor division
# is pinned independently in tests/test_kimg.py (also for negative values).
@lru_cache(maxsize=4096)
def _yjk_decoded_ramp(j, k):
    return tuple(yjk_decode(y, j, k) for y in range(32))


_SQUARED_DIFFS = tuple(tuple((a - b) ** 2 for b in range(32))
                      for a in range(32))


def _yjk_best_y(pixel, ramp):
    """Exhaustive luminance search, preferring the lowest Y on a tie."""
    red, green, blue = (_SQUARED_DIFFS[c] for c in pixel)
    best_error = 3 * 31 * 31 + 1
    best_y = 0
    for y, (r, g, b) in enumerate(ramp):
        error = red[r] + green[g] + blue[b]
        if error < best_error:
            best_y, best_error = y, error
            if not error:
                break
    return best_y, best_error


@lru_cache(maxsize=4096)
def _yjk_optimized_group(pixels):
    """Search a four-pixel RGB555 group; cache immutable results, bounded.

    The initial chroma is the average of the per-pixel estimates. This is
    algebraically the fast encoder's chroma on the *same RGB555 input*, so
    its J/K is always in the candidate set. Searching every Y at that pair
    ensures error cannot exceed fast on identical RGB555, even though the
    two RGB888 conversion paths quantize their input differently.

    Visit J, then K, in ascending order; retain the first minimum. Together
    with ascending Y this defines deterministic lexicographic tie-breaking.
    """
    estimates = tuple(b / 2 + r / 4 + g / 8 for r, g, b in pixels)
    initial_j = max(-32, min(31, round(sum(p[0] - y for p, y in
                                         zip(pixels, estimates)) / 4)))
    initial_k = max(-32, min(31, round(sum(p[1] - y for p, y in
                                         zip(pixels, estimates)) / 4)))
    best_error = 4 * 3 * 31 * 31 + 1
    best = None
    for j in range(max(-32, initial_j - 3), min(31, initial_j + 3) + 1):
        for k in range(max(-32, initial_k - 3), min(31, initial_k + 3) + 1):
            ramp = _yjk_decoded_ramp(j, k)
            luminances, error = [], 0
            for pixel in pixels:
                y, pixel_error = _yjk_best_y(pixel, ramp)
                luminances.append(y)
                error += pixel_error
                if error >= best_error:
                    break
            if error < best_error:
                best_error = error
                best = (j, k, luminances)
    j, k, luminances = best
    lows = (k & 7, (k >> 3) & 7, j & 7, (j >> 3) & 7)
    return bytes((y << 3) | low for y, low in zip(luminances, lows))


def _yjk_run_optimized(pixels):
    """Accept the same RGB555 group API as the fast encoder."""
    return _yjk_optimized_group(tuple(pixels))


def _pack_yjk(rgb, size, quality="fast"):
    width, height = size
    raw = rgb.tobytes()
    payload = bytearray()
    optimized = quality == "optimized"
    # Integer nearest-value rounding to the full 0..31 range. The legacy
    # fast path deliberately retains its original truncating >> 3 rule.
    quantize = tuple((value * 31 + 127) // 255 for value in range(256))
    for row in range(height):
        base = row * width * 3
        for x in range(0, width, YJK_RUN):
            run = []
            for pixel in range(x, x + YJK_RUN):
                at = base + pixel * 3
                if optimized:
                    run.append((quantize[raw[at]], quantize[raw[at + 1]],
                                quantize[raw[at + 2]]))
                else:
                    run.append((raw[at] >> 3, raw[at + 1] >> 3, raw[at + 2] >> 3))
            payload += _yjk_run_optimized(run) if optimized else _yjk_run(run)
    return [], bytes(payload)


PACKERS = {"g6": _pack_g6, "g7": _pack_g7, "yjk": _pack_yjk}


def _write_image(output, mode_value, width, height, palette, payload):
    header = (MAGIC + bytes([VERSION, mode_value, FLAGS, len(palette) // 3])
              + struct.pack("<HH", width, height)
              + struct.pack("<I", len(payload)))
    with open(output, "wb") as handle:
        handle.write(header + bytes(palette) + payload)


def convert(source, output, mode, size=None, *, resample="nearest",
            sharpen=False, sharpen_radius=0.8, sharpen_percent=120,
            sharpen_threshold=2, yjk_quality="fast"):
    require_pillow()
    if resample not in ("nearest", "box", "lanczos"):
        raise SystemExit("kimg: unknown resampling filter %s" % resample)
    if yjk_quality not in ("fast", "optimized"):
        raise SystemExit("kimg: unknown YJK quality %s" % yjk_quality)
    if not math.isfinite(sharpen_radius) or sharpen_radius < 0 or \
            sharpen_percent < 0 or not 0 <= sharpen_threshold <= 255:
        raise SystemExit("kimg: sharpening requires finite radius >= 0, "
                         "percent >= 0 and threshold in 0..255")
    mode_value, width, height = MODES[mode]
    if size is not None:
        width, height = size
    if width <= 0 or height <= 0 or (mode == "g6" and width % 2) or \
            (mode == "yjk" and width % YJK_RUN):
        raise SystemExit("kimg: bad geometry %dx%d for %s"
                         % (width, height, mode))
    with Image.open(source) as image:
        rgb = _fit(image.convert("RGB"), (width, height), resample)
    if sharpen:
        rgb = rgb.filter(ImageFilter.UnsharpMask(radius=sharpen_radius,
                         percent=sharpen_percent, threshold=sharpen_threshold))
    if mode == "yjk":
        palette, payload = _pack_yjk(rgb, (width, height), yjk_quality)
    else:
        palette, payload = PACKERS[mode](rgb, (width, height))
    _write_image(output, mode_value, width, height, palette, payload)


def pack(source, output, mode, size=None, palette_source=None):
    """Wrap native pixels in KIMG v1 without interpreting their colours.

    Geometry follows PView's supported screen bounds and packing alignment.
    Validate all inputs before opening the output, including exact lengths:
    this prevents quietly treating a file header or trailing palette as pixels.
    """
    mode_value, screen_width, screen_height = MODES[mode]
    width, height = size if size is not None else (screen_width, screen_height)
    if not (0 < width <= screen_width and 0 < height <= screen_height) or \
            (mode == "g6" and width % 2) or \
            (mode == "yjk" and width % YJK_RUN):
        raise SystemExit("kimg: bad geometry %dx%d for %s"
                         % (width, height, mode))
    if palette_source is not None and mode != "g6":
        raise SystemExit("kimg: --palette is only supported for g6")
    palette = b""
    if palette_source is not None:
        with open(palette_source, "rb") as handle:
            palette = handle.read()
        if not palette or len(palette) > 48 or len(palette) % 3:
            raise SystemExit("kimg: palette must contain 1-16 RGB888 triples "
                             "(3-48 bytes)")
    with open(source, "rb") as handle:
        payload = handle.read()
    expected = (width // 2 if mode == "g6" else width) * height
    if len(payload) != expected:
        raise SystemExit("kimg: %s: expected %d native pixel bytes for "
                         "%dx%d %s, got %d (check --size and input headers)"
                         % (source, expected, width, height, mode, len(payload)))
    _write_image(output, mode_value, width, height, palette, payload)


def _info(path):
    with open(path, "rb") as handle:
        data = handle.read()
    if len(data) < 16:
        raise SystemExit("kimg: %s: truncated header" % path)
    magic, version, mode, flags, palette_count = struct.unpack(
        "<4sBBBB", data[:8])
    width, height, payload_size = struct.unpack("<HHI", data[8:16])
    names = {value: name for name, (value, _w, _h) in MODES.items()}
    print("%s: KIMG v%u mode=%s flags=%u palette=%u %ux%u payload=%u"
          % (path, version, names.get(mode, mode), flags, palette_count,
             width, height, payload_size))
    if magic != MAGIC:
        raise SystemExit("kimg: %s: bad magic" % path)


def main(argv):
    parser = argparse.ArgumentParser(prog="kimg.py",
                                     description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)
    convert_parser = sub.add_parser("convert")
    convert_parser.add_argument("source")
    convert_parser.add_argument("output")
    convert_parser.add_argument("--mode", choices=sorted(MODES),
                                required=True)
    convert_parser.add_argument("--size", default=None,
                                help="WxH (default: the mode's screen)")
    convert_parser.add_argument("--resample", choices=("nearest", "box", "lanczos"),
                                default="nearest",
                                help="nearest: hard edges (default); box: area average; "
                                     "lanczos: smooth reduction, possible ringing")
    convert_parser.add_argument("--sharpen", action="store_true",
                                help="unsharp mask after resizing (may produce halos)")
    convert_parser.add_argument("--sharpen-radius", type=float, default=0.8,
                                help="unsharp radius, >= 0 (default: 0.8)")
    convert_parser.add_argument("--sharpen-percent", type=int, default=120,
                                help="unsharp amount, >= 0 (default: 120)")
    convert_parser.add_argument("--sharpen-threshold", type=int, default=2,
                                help="unsharp threshold, 0..255 (default: 2)")
    convert_parser.add_argument("--yjk-quality", choices=("fast", "optimized"),
                                default="fast",
                                help="YJK encoder (default: fast; optimized searches chroma/Y)")
    pack_parser = sub.add_parser("pack", help="wrap native pixel bytes unchanged")
    pack_parser.add_argument("source", help="headerless native pixel file")
    pack_parser.add_argument("output")
    pack_parser.add_argument("--mode", choices=sorted(MODES), required=True)
    pack_parser.add_argument("--size", default=None,
                             help="WxH (default: the mode's screen)")
    pack_parser.add_argument("--palette", default=None,
                             help="G6 only: binary RGB888 triples (1-16 colours)")
    info_parser = sub.add_parser("info")
    info_parser.add_argument("file")
    args = parser.parse_args(argv)
    if args.command in ("convert", "pack"):
        size = None
        if args.size is not None:
            try:
                size = tuple(int(part) for part in args.size.split("x"))
            except ValueError:
                raise SystemExit("kimg: --size must be WxH")
            if len(size) != 2:
                raise SystemExit("kimg: --size must be WxH")
        if args.command == "convert":
            convert(args.source, args.output, args.mode, size,
                    resample=args.resample, sharpen=args.sharpen,
                    sharpen_radius=args.sharpen_radius,
                    sharpen_percent=args.sharpen_percent,
                    sharpen_threshold=args.sharpen_threshold,
                    yjk_quality=args.yjk_quality)
        else:
            try:
                pack(args.source, args.output, args.mode, size, args.palette)
            except OSError as error:
                raise SystemExit("kimg: %s" % error) from None
        print("kimg: %s -> %s (%s)" % (args.source, args.output,
                                       args.mode))
    else:
        _info(args.file)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
