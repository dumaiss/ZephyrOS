#!/usr/bin/env python3
"""KonaOS shell logo asset pipeline.

The reviewable source asset is user/shell/konaos-logo-80x46.lmmc: the
80 x 46, 4-bit-per-pixel KonaOS logo as the V9958 GRAPHIC 6 LMMC byte
stream - one pixel per byte in the low nibble, row by row, exactly what
the VDP's LMMC command reads from R#44 (the first pixel rides in R#44
before the command starts, the rest stream through R#44 while it runs).

The shell writes the logo straight into VRAM through the data port (the
hardware WAIT paces it), so this tool packs the dump into GRAPHIC 6's own
layout - two pixels per byte, the left one in the high nibble, 40 bytes
per row - and emits the deterministic C pair the shell links into its
primary image:

    g6pack.py <source.lmmc> <logo.h> <logo.c>   pack + verify
    g6pack.py verify <source.lmmc>              parse + verify only

The emitted logo.c defines `konaos_logo`, and logo.h declares it beside
the width, height, row and byte counts.  The pinned SHA-256 of the 3680-byte
payload is
03fb9ce73ce9506662c9304a577506f064275484ab8398691d2777bab01b5d12;
a mismatch is an error, never a warning.
"""

import hashlib
import sys
from pathlib import Path

WIDTH = 80
HEIGHT = 46
BYTES = WIDTH * HEIGHT
ROW_BYTES = WIDTH // 2
PACKED_BYTES = ROW_BYTES * HEIGHT
PINNED_SHA256 = (
    "03fb9ce73ce9506662c9304a577506f064275484ab8398691d2777bab01b5d12"
)

HEADER = """\
/* KonaOS native shell: the banner logo, generated by tools/g6pack.py
 * from user/shell/konaos-logo-80x46.lmmc.  Do not edit by hand.
 *
 * The bitmap is 80 x 46 pixels in GRAPHIC 6's VRAM layout: two pixels
 * per byte, the left one in the high nibble, KONAOS_LOGO_ROW_BYTES bytes
 * per row, row by row.
 */

#ifndef SHELL_LOGO_H
#define SHELL_LOGO_H

#define KONAOS_LOGO_WIDTH 80u
#define KONAOS_LOGO_HEIGHT 46u
#define KONAOS_LOGO_ROW_BYTES 40u
#define KONAOS_LOGO_BYTES 1840u

extern const unsigned char konaos_logo[KONAOS_LOGO_BYTES];

#endif /* SHELL_LOGO_H */
"""

SOURCE = """\
/* KonaOS native shell: the banner logo bitmap, generated by
 * tools/g6pack.py from user/shell/konaos-logo-80x46.lmmc (SHA-256
 * %s).  Do not edit by hand; regenerate with
 *
 *     python3 tools/g6pack.py user/shell/konaos-logo-80x46.lmmc \\
 *         user/shell/logo.h user/shell/logo.c
 */

#include "logo.h"

const unsigned char konaos_logo[KONAOS_LOGO_BYTES] = {
%s
};
"""


class G6Error(Exception):
    pass


def parse_g6(path):
    with open(path, "rb") as handle:
        data = handle.read()
    if len(data) != BYTES:
        raise G6Error("%s: expected %d bytes, found %d"
                      % (path, BYTES, len(data)))
    for byte in data:
        if byte & 0xF0:
            raise G6Error("%s: pixel byte 0x%02X carries high bits"
                          % (path, byte))
    return data


def verify(data, path):
    digest = hashlib.sha256(data).hexdigest()
    if digest != PINNED_SHA256:
        raise G6Error("%s: SHA-256 %s does not match the pinned reference %s"
                      % (path, digest, PINNED_SHA256))
    return digest


def pack(data):
    """The LMMC dump (one pixel per byte) as GRAPHIC 6 VRAM bytes."""
    return bytes((data[i] << 4) | data[i + 1] for i in range(0, BYTES, 2))


def render_source(data):
    packed = pack(data)
    assert len(packed) == PACKED_BYTES
    rows = []
    for offset in range(0, PACKED_BYTES, 12):
        chunk = packed[offset:offset + 12]
        rows.append("    " + ", ".join("0x%02Xu" % byte for byte in chunk))
    return SOURCE % (PINNED_SHA256, ",\n".join(rows))


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    command = argv[1]
    if command == "verify":
        if len(argv) != 3:
            print(__doc__)
            return 2
        data = parse_g6(argv[2])
        verify(data, argv[2])
        print("%s: %d bytes, SHA-256 verified" % (argv[2], len(data)))
        return 0
    if command == "pack":
        if len(argv) != 5:
            print(__doc__)
            return 2
        data = parse_g6(argv[2])
        verify(data, argv[2])
        Path(argv[3]).write_text(HEADER, encoding="ascii")
        Path(argv[4]).write_text(render_source(data), encoding="ascii")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
