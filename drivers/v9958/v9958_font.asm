; -----------------------------------------------------------------------------
; KonaOS V9958 mapped segment (architecture 5.6).
;
; The driver's text renderer reads these inside a bulk-map span, at their
; linked addresses in bank 6's mapped range (0100h-1FFFh).  The segment
; asks the planner for a 256-byte aligned base, so every table below is a
; set of whole 256-byte pages and a byte is found by setting H to the
; page and L to the index.
;
;   _v9958_font_pages  the pinned CP850 6x8 font, scanline-major: eight
;                      pages, page s holding row s of every character
;                      (generated by tools/fontpack.py paged);
;   _v9958_expand      the expansion pages, built at init: three pages per
;                      colour pair, page b mapping a font row byte (bits
;                      7..2 are the six pixels) to output byte b of the
;                      cell (two pixels, the left one in the high nibble);
;                      the normal pair first, then the reverse pair.
; -----------------------------------------------------------------------------

	.module v9958_font

	.area _MAPPED

	.globl _v9958_font_pages
_v9958_font_pages::
	.include "v9958_font_pages.inc"

	.area _MAPPED_BSS

	.globl _v9958_expand
_v9958_expand::
	.ds	1536
