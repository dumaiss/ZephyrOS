#!/usr/bin/env python3
"""Emit expected-container constants for the M5 target selftest.

Usage: gen_expect.py <container> <output.inc> <PREFIX>

Writes a C include defining <PREFIX>_SIZE (bytes) and <PREFIX>_SUM
(16-bit byte sum) so the target image can verify that the ROMFS copy of
the boot module matches the packed container byte-for-byte (size plus
content checksum; the host tests verify the stronger SHA-256 identity).
"""

import sys
from pathlib import Path


def main(argv):
    if len(argv) != 4:
        print(__doc__)
        return 2
    data = Path(argv[1]).read_bytes()
    total = sum(data) & 0xFFFF
    text = (
        "/* Generated by tests/m5/gen_expect.py; do not edit. */\n"
        "#ifndef ZEPHYROS_M5_EXPECT_INC\n"
        "#define ZEPHYROS_M5_EXPECT_INC\n"
        "#define %s_SIZE %d\n"
        "#define %s_SUM 0x%04X\n"
        "#endif\n" % (argv[3], len(data), argv[3], total)
    )
    Path(argv[2]).write_text(text)
    print("gen_expect: %s: %d bytes, sum 0x%04X"
          % (argv[1], len(data), total))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
