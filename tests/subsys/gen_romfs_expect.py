#!/usr/bin/env python3
"""Emit expected-container constants for the ROMFS-reader target selftest.

Usage: gen_romfs_expect.py <manifest.json> <container> <output.inc> <PREFIX>

Writes a C include defining <PREFIX>_SIZE (bytes) and <PREFIX>_SUM
(16-bit byte sum) so the target image can verify that the ROMFS copy of
the boot module matches the packed container byte-for-byte (size plus
content checksum; the host tests verify the stronger SHA-256 identity),
plus CROSSPAGE_OFFSET, the file-relative offset of the 48-KiB logical
window boundary inside the first manifest entry.  The offset is derived
from the manifest (16-byte header + one 36-byte directory entry per
file, payloads packed in order) so it cannot drift when the acceptance
manifest grows.
"""

import json
import sys
from pathlib import Path

HEADER_SIZE = 16
ENTRY_SIZE = 36


def main(argv):
    if len(argv) != 5:
        print(__doc__)
        return 2
    manifest = json.loads(Path(argv[1]).read_text())
    data = Path(argv[2]).read_bytes()
    total = sum(data) & 0xFFFF
    payload_offset = HEADER_SIZE + ENTRY_SIZE * len(manifest["files"])
    text = (
        "/* Generated by tests/subsys/gen_romfs_expect.py; do not edit. */\n"
        "#ifndef ZEPHYROS_ROMFS_EXPECT_INC\n"
        "#define ZEPHYROS_ROMFS_EXPECT_INC\n"
        "#define %s_SIZE %d\n"
        "#define %s_SUM 0x%04X\n"
        "#define CROSSPAGE_OFFSET %d\n"
        "#endif\n" % (argv[4], len(data), argv[4], total, payload_offset)
    )
    Path(argv[3]).write_text(text)
    print("gen_expect: %s: %d bytes, sum 0x%04X, first payload at %d"
          % (argv[2], len(data), total, payload_offset))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
