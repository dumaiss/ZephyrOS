#!/usr/bin/env python3
"""Generate the process target-test layout header (test artifact).

Reads the packed EXE v2 containers the process acceptance exercises plus
the fixture table (tests/subsys/gen_exe_fixtures.py) and writes the C
include used by process_test.c:

    <PREFIX>_IMAGE_SIZE / _BSS_SIZE / _BSS_START / _BSS_END
    <PREFIX>_STACK_SIZE / _STACK_TOP / _STACK_BASE / _ENTRY_ADDR
    <PREFIX>_SEG_COUNT and <PREFIX>_SEG<i>_IMAGE / _BSS / _SLOTS
    process_fixtures[]  (ROMFS name -> exact process_exec rejection code)

The geometry comes from the containers themselves, so the test can only
agree with what the loader will actually read.

Usage:
    gen_process_expect.py <out.inc> <PREFIX>=<program.exe> [...]
"""

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(HERE))
import exepack  # noqa: E402
import gen_exe_fixtures as gen_fixtures  # noqa: E402

LOAD_BASE = 0x0100
STACK_TOP = 0xE000


def emit_program(lines, prefix, path):
    data = Path(path).read_bytes()
    fields, _geometry = exepack.validate_image(data)
    image_size = fields["image_size"]
    bss_start = LOAD_BASE + image_size
    lines += [
        "#define %s_IMAGE_SIZE 0x%04Xu" % (prefix, image_size),
        "#define %s_BSS_SIZE   0x%04Xu" % (prefix, fields["bss_size"]),
        "#define %s_BSS_START  0x%04Xu" % (prefix, bss_start),
        "#define %s_BSS_END    0x%04Xu"
        % (prefix, bss_start + fields["bss_size"]),
        "#define %s_STACK_SIZE 0x%04Xu" % (prefix, fields["stack_size"]),
        "#define %s_STACK_TOP  0x%04Xu" % (prefix, STACK_TOP),
        "#define %s_STACK_BASE 0x%04Xu"
        % (prefix, STACK_TOP - fields["stack_size"]),
        "#define %s_ENTRY_ADDR 0x%04Xu"
        % (prefix, LOAD_BASE + fields["entry_offset"]),
        "#define %s_SEG_COUNT  %du" % (prefix, fields["segment_count"]),
    ]
    for index in range(fields["segment_count"]):
        row = exepack.parse_segment_row(
            data, fields["segment_table_offset"] +
            index * exepack.SEGMENT_ENTRY_SIZE)
        lines += [
            "#define %s_SEG%d_IMAGE 0x%04Xu"
            % (prefix, index + 1, row["image_size"]),
            "#define %s_SEG%d_BSS   0x%04Xu"
            % (prefix, index + 1, row["bss_size"]),
            "#define %s_SEG%d_SLOTS %du"
            % (prefix, index + 1,
               exepack.segment_slots(row["image_size"], row["bss_size"])),
        ]


def main(argv):
    if len(argv) < 2 or "=" not in argv[1]:
        print(__doc__)
        return 2
    lines = [
        "/* generated by tests/subsys/gen_process_expect.py; do not edit */",
        "#ifndef KONAOS_TARGET_PROCESS_EXPECT_INC",
        "#define KONAOS_TARGET_PROCESS_EXPECT_INC",
        "",
    ]
    for argument in argv[1:]:
        prefix, path = argument.split("=", 1)
        emit_program(lines, prefix, path)

    fixtures = [f for f in gen_fixtures.build_fixtures()
                if f["kernel_code"] is not None]
    lines += [
        "",
        "#define PROCESS_FIXTURE_COUNT %du" % len(fixtures),
        "static const struct exe_fixture_desc "
        "process_fixtures[PROCESS_FIXTURE_COUNT] = {",
    ]
    for fixture in fixtures:
        code = exepack.CODE_BY_NAME[fixture["kernel_code"]]
        lines.append('\t{ "%s", %d }, /* %s */'
                     % (fixture["name"], code, fixture["kernel_code"]))
    lines += [
        "};",
        "",
        "#endif /* KONAOS_TARGET_PROCESS_EXPECT_INC */",
        "",
    ]
    out = Path(argv[0])
    if out.parent and not out.parent.exists():
        out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print("gen_expect: %s: %d programs, %d fixtures"
          % (out, len(argv) - 1, len(fixtures)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
