#!/usr/bin/env python3
"""Generate the process target-test layout header (test artifact).

Reads the single source of truth for the zextest program layout
(tests/subsys/zextest.json) plus the fixture table
(tests/subsys/gen_zex_fixtures.py)
and writes the C include used by zextest.c and process_test.c:

    PROCESS_ZEX_IMAGE_SIZE / PROCESS_ZEX_BSS_SIZE / PROCESS_ZEX_STACK_SIZE
    PROCESS_ZEX_STACK_BASE / PROCESS_ZEX_STACK_TOP / PROCESS_ZEX_ENTRY_ADDR
    process_fixtures[]  (ROMFS name -> exact process_exec rejection code)

Usage:
    gen_process_expect.py <zextest.json> <out.inc>
"""

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(HERE))
import zexpack  # noqa: E402
import gen_zex_fixtures as gen_fixtures  # noqa: E402

LOAD_BASE = 0x0100
STACK_TOP = 0xE000


def main(argv):
    if len(argv) != 2:
        print(__doc__)
        return 2
    manifest = zexpack.load_manifest(argv[0])
    fixtures = [f for f in gen_fixtures.build_fixtures()
                if f["kernel_code"] is not None]

    image_size = manifest["image_size"]
    bss_size = manifest["bss_size"]
    stack_size = manifest["stack_size"]
    entry = LOAD_BASE + manifest["entry_offset"]

    lines = [
        "/* generated by tests/subsys/gen_process_expect.py; do not edit */",
        "#ifndef ZEPHYROS_TARGET_PROCESS_EXPECT_INC",
        "#define ZEPHYROS_TARGET_PROCESS_EXPECT_INC",
        "",
        "#define PROCESS_ZEX_IMAGE_SIZE 0x%04Xu" % image_size,
        "#define PROCESS_ZEX_BSS_SIZE   0x%04Xu" % bss_size,
        "#define PROCESS_ZEX_STACK_SIZE 0x%04Xu" % stack_size,
        "#define PROCESS_ZEX_STACK_TOP  0x%04Xu" % STACK_TOP,
        "#define PROCESS_ZEX_STACK_BASE 0x%04Xu" % (STACK_TOP - stack_size),
        "#define PROCESS_ZEX_ENTRY_ADDR 0x%04Xu" % entry,
        "",
        "#define PROCESS_FIXTURE_COUNT %du" % len(fixtures),
        "static const struct zex_fixture_desc process_fixtures[PROCESS_FIXTURE_COUNT] = {",
    ]
    for fixture in fixtures:
        code = zexpack.CODE_BY_NAME[fixture["kernel_code"]]
        lines.append('\t{ "%s", %d }, /* %s */'
                     % (fixture["name"], code, fixture["kernel_code"]))
    lines += [
        "};",
        "",
        "#endif /* ZEPHYROS_TARGET_PROCESS_EXPECT_INC */",
        "",
    ]
    out = Path(argv[1])
    if out.parent and not out.parent.exists():
        out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print("gen_expect: %s: image %d, bss %d, stack %d, %d fixtures"
          % (out, image_size, bss_size, stack_size, len(fixtures)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
