#!/usr/bin/env python3
"""Generate user/sdk/snd/src/snd_tables.c (the A440 note-divisor table
and the linear-level-to-attenuation table).

Checked-in generator; the generated source is committed.  Regenerate
with:

    python3 tests/snd/gen_tables.py > user/sdk/snd/src/snd_tables.c

The divisor table is the SN76489 period for the 3,579,545 Hz PSG clock:

    frequency(n) = 440 * 2 ** ((n - 48) / 12)
    period(n)    = round(3579545 / (32 * frequency(n))), clamped 1-1023

The level table maps the user-facing linear loudness 0..255 to the
SN76489 attenuation (0 = loudest):

    attenuation(level) = 15 - round(level * 15 / 255)
"""

import sys

CLOCK = 3579545
A4 = 440.0

HEADER = """/* libsnd built-in tables (generated by tests/snd/gen_tables.py).
 *
 * snd_a440_table: the 96 SN76489 tone divisors for notes C-0 (index 0)
 * through B-7 (index 95) at A440 on the 3,579,545 Hz PSG clock, the
 * clock the Afternoon Blend card reports.  period = 3579545 / (32 * f),
 * rounded and clamped to 1-1023; the same formula ZTR-Format.md names.
 *
 * snd_level_table: the linear user loudness 0..255 (255 loudest) mapped
 * to the SN76489 attenuation byte (0 loudest): 15 - round(level*15/255).
 * The voice engine applies this on every ATTEN step, so manual
 * instruments move through at most the 16 hardware levels.
 */

#include "snd_private.h"

const uint16_t snd_a440_table[SND_NOTE_COUNT] = {
"""


def period(note):
    freq = A4 * 2 ** ((note - 48) / 12)
    value = round(CLOCK / (32.0 * freq))
    return max(1, min(1023, value))


def attenuation(level):
    return 15 - int(round(level * 15 / 255))


def format_rows(values, per_row, width):
    lines = []
    for start in range(0, len(values), per_row):
        lines.append("\t" + ", ".join(
            "%*d" % (width, value) for value in values[start:start + per_row]
        ) + ",")
    return "\n".join(lines)


def main():
    out = [HEADER]
    out.append(format_rows([period(n) for n in range(96)], 8, 4))
    out.append("};\n\nconst uint8_t snd_level_table[256] = {\n")
    out.append(format_rows([attenuation(l) for l in range(256)], 16, 2))
    out.append("};")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
