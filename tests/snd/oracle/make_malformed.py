#!/usr/bin/env python3
"""Print the malformed-fixture outcomes table (tests/snd/golden/malformed.md).

Runs the two host oracles over every fixture in tests/snd/fixtures/malformed
and prints the pinned markdown table: one row per fixture with the stage the
oracle reached and its result line.  Regenerate the checked-in table with:

    python3 tests/snd/oracle/make_malformed.py > tests/snd/golden/malformed.md
"""

import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
SND = os.path.join(ROOT, "tests", "snd")
MALFORMED = os.path.join(SND, "fixtures", "malformed")
ZTR = os.path.join(ROOT, "build", "host", "snd", "ztr_trace")
ZVG = os.path.join(ROOT, "build", "host", "snd", "zvg_trace")

HEADER = """# Malformed-fixture outcomes (the oracles)

Generated by tests/snd/oracle/make_malformed.py from the oracles'
current output; tests/test_snd_oracle.py pins it.  `stage` is the check
the oracle reached, `result` its outcome line (`ztr:` carries the
player's error string and code, `zvg:` the header refusal or the bad
opcode with its stream offset).

| Fixture | Stage | Result |
| --- | --- | --- |
"""


def run(tool, path):
    result = subprocess.run([tool, path], stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT, text=True)
    return result.returncode, result.stdout


def ztr_row(name, stdout):
    line = stdout.splitlines()[0]
    assert line.startswith("ztr: "), (name, line)
    message, code = line[5:].rsplit(" (", 1)
    return "ztr-load", "%s (%s" % (message, code)


def zvg_row(name, stdout):
    for line in stdout.splitlines():
        if line.startswith("zvg: "):
            if line.startswith("zvg: open "):
                return "zvg-open", line
            if line.startswith("zvg: opcode "):
                return "zvg-decode", line
    raise AssertionError((name, stdout))


def main():
    rows = []
    for name in sorted(os.listdir(MALFORMED)):
        path = os.path.join(MALFORMED, name)
        tool = ZTR if name.endswith(".ztr") else ZVG
        code, stdout = run(tool, path)
        if code == 0:
            raise AssertionError("%s was accepted by the oracle" % name)
        if name.endswith(".ztr"):
            stage, result = ztr_row(name, stdout)
        else:
            stage, result = zvg_row(name, stdout)
        rows.append((name, stage, result))
    sys.stdout.write(HEADER)
    for name, stage, result in rows:
        sys.stdout.write("| %s | %s | `%s` |\n" % (name, stage, result))


if __name__ == "__main__":
    main()
