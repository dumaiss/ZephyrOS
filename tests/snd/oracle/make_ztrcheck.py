#!/usr/bin/env python3
"""Print the ztrcheck verdict table (tests/snd/golden/ztrcheck.md).

Runs the ZTRCheck host twin over the two good ZTR fixtures and every
malformed one, and prints the pinned markdown table: one row per fixture
with the verdict line (the OK summary's CRC state for good files, the
FAIL line for defective ones).  Regenerate the checked-in table with:

    python3 tests/snd/oracle/make_ztrcheck.py > tests/snd/golden/ztrcheck.md

The host twin is UserSoftware/ZTRCheck/build/host/ztrcheck (make -C
UserSoftware/ZTRCheck host).
"""

import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
SND = os.path.join(ROOT, "tests", "snd")
FIXTURES = os.path.join(SND, "fixtures")
MALFORMED = os.path.join(FIXTURES, "malformed")
ZTRCHECK = os.path.join(ROOT, "UserSoftware", "ZTRCheck", "build",
                        "host", "ztrcheck")

HEADER = """# ztrcheck verdicts

Generated by tests/snd/oracle/make_ztrcheck.py from the host twin's
current output; tests/test_snd.py pins it.  The loader's structural
validation lives in ztrcheck: `verdict` is the last output line, the
OK summary's tail for a valid file, the FAIL line for a defective one.

| Fixture | Verdict |
|---|---|
"""


def verdict(path):
    result = subprocess.run([ZTRCHECK, path], stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT, check=False)
    return result.stdout.decode().splitlines()[-1]


def main():
    rows = []
    for name in ("night-market.ztr", "RunawayCircuit.ztr"):
        rows.append((name, verdict(os.path.join(FIXTURES, name))))
    for name in sorted(item for item in os.listdir(MALFORMED)
                       if item.endswith(".ztr")):
        rows.append((name, verdict(os.path.join(MALFORMED, name))))
    sys.stdout.write(HEADER)
    for name, line in rows:
        print("| %s | `%s` |" % (name, line))


if __name__ == "__main__":
    main()
